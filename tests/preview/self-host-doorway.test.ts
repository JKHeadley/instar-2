// Regression: J-proofroom2-j-binding-1021-20261021-195327 refused Codex before any provider call.
import { afterEach, expect, it } from 'vitest';
import { mkdtempSync, readFileSync, realpathSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { subscriptionDoorway } from '../../src/assembly/production-provider.js';
import { CODEX_SUBSCRIPTION_VERSION, CODEX_LOGIN_STATUS_STDERR_LINE } from '../../src/assembly/production-codex-provider.js';
import { doorwayProvider, SELF_HOST_QUESTION, selfHostPrompt } from './self-host.mjs';
import { dispatchOwnedProvider, providerStores } from './self-host-owners.ts';
import { encoded, inputMeasurements, requireInputBound } from './stage2-provider.js';
import { successiveWorld, offlineProfile } from './successive-fixture.js';

const roots = [];
afterEach(() => roots.splice(0).forEach(root => rmSync(root, { recursive: true, force: true })));
const regression = JSON.parse(readFileSync('tests/preview/fixtures/self-host-codex-2026-10-21.json', 'utf8'));
const now = () => 1790000002000, doorwayId = regression.doorway, model = regression.model;
const captured = JSON.parse(readFileSync('tests/preview/fixtures/codex-answer-0.156.1.json', 'utf8'));
const plans = JSON.parse(readFileSync('tests/preview/fixtures/self-host-flat-live-2026-10-06.json', 'utf8'));
const corpus = JSON.parse(readFileSync('tests/preview/fixtures/retrospective-duty-followup-train-1-2026-10-08.json', 'utf8'));
function fixture() {
  const root = realpathSync(mkdtempSync(join(tmpdir(), 'self-host-doorway-'))); roots.push(root);
  const doorway = subscriptionDoorway(doorwayId);
  const profile = Object.freeze({ ...offlineProfile, version: CODEX_SUBSCRIPTION_VERSION });
  const activation = { ...successiveWorld(root).activation(), model, version: profile.version,
    profileDigest: encoded(profile).hash, invocationPolicyDigest: encoded(doorway.policyFor(model, doorway.conversationFraming)).hash };
  const state = { calls: 0, stopped: false, raw: captured.captures.at(-1).stdout, auth: 'chatgpt', code: 0 };
  const io = { realpath: p => p, executableBytes: () => Buffer.from('offline executable bytes'),
    inspectSubscriptionProfile: p => ({ loginProfileIdentity: p.loginProfileIdentity, managedConfigurationDigest: p.managedConfigurationDigest }),
    codexAuthMode: () => state.auth,
    execute: async command => {
      let stdout = '', stderr = '';
      if (command.args[0] === '--version') stdout = `codex-cli ${CODEX_SUBSCRIPTION_VERSION}\n`;
      else if (command.args[0] === 'login') stderr = CODEX_LOGIN_STATUS_STDERR_LINE + '\n';
      else { state.calls++; stdout = state.raw; }
      return { code: command.stdin ? state.code : 0, limited: false, stdout, stderr,
        stdoutBytes: new Uint8Array(Buffer.from(stdout)), stderrBytes: new Uint8Array(Buffer.from(stderr)) };
    } };
  const input = { doorwayId, io, profile, activation, model, stopped: () => state.stopped, now };
  const dispatch = async (provider) => dispatchOwnedProvider({ root, task: 'recorded-codex-self-host',
    question: SELF_HOST_QUESTION, conversation: [{ request: JSON.parse(selfHostPrompt('Build a word-count capability.', null)) }],
    allowance: 3, provider: provider ?? await doorwayProvider(input), stopped: input.stopped, now });
  // Historical model bytes inside the recorded Codex transport envelope, not a claim they were generated by Codex.
  const answer = raw => { state.raw = captured.captures.at(-1).stdout.trim().split('\n').map(line => {
    const event = JSON.parse(line);
    return JSON.stringify(event.type === 'item.completed' && event.item.type === 'agent_message'
      ? { ...event, item: { ...event.item, text: raw } } : event);
  }).join('\n') + '\n'; };
  return { root, input, state, dispatch, answer };
}

it('reaches the registered Codex doorway with the recorded 0.156.1 transport and retains its exact owner binding', async () => {
  const f = fixture(), provider = await doorwayProvider(f.input);
  expect(provider.doorway).toBe(doorwayId);
  expect(f.input.profile.version).toBe(regression.version);
  expect(f.input.activation.invocationPolicyDigest).toBe(regression.invocationPolicyDigest);
  await f.dispatch(provider);
  expect(f.state.calls).toBe(1);
  const facts = providerStores(f.root)[0].facts;
  const request = facts.find(row => row.kind === 'judgment-provider-ProviderJudgmentRequest').body.record;
  expect(request.provider).toBe('openai');
  expect(facts.filter(row => row.kind === 'transport-AdmissionReservation').map(row => row.body.record.state))
    .toEqual(['prepared', 'dispatch-claimed', 'consumed']);
  const binding = facts.find(row => row.kind === 'evidence-record' && row.body.evidence.claim.predicate === 'preview-invocation-binding').body.evidence.claim.value;
  expect(binding).toMatchObject({ doorway: doorwayId, invocationPolicyDigest: f.input.activation.invocationPolicyDigest });
});

it.each(['model', 'policy', 'profile', 'expired', 'stopped', 'unknown-doorway'])('refuses %s before physical execution', async kind => {
  const f = fixture(), input = { ...f.input, activation: { ...f.input.activation } };
  if (kind === 'model') input.model = 'gpt-other-exact';
  if (kind === 'policy') input.activation.invocationPolicyDigest = encoded('other').hash;
  if (kind === 'profile') input.profile = Object.freeze({ ...input.profile, expectedAccount: 'another@example.invalid' });
  if (kind === 'expired') input.now = () => input.activation.expiresAt;
  if (kind === 'stopped') f.state.stopped = true;
  if (kind === 'unknown-doorway') input.doorwayId = 'unregistered';
  await expect(doorwayProvider(input)).rejects.toThrow();
  expect(f.state.calls).toBe(0);
});

// Use the suite's bounded host allowance: these cases prove durable evidence, not elapsed latency.
// The same recorded plan completed in 9 s and 58 s on the Laptop without changing source or assertions.
it.each(plans.recorded)('replays the real self-host plan $label through Codex and its provider owners', async row => {
  const f = fixture(); f.answer(row.output);
  const result = await f.dispatch();
  expect(JSON.parse(result.answer).package.namespace).toBe('agent.word-count');
  expect(f.state.calls).toBe(1);
});

it.each(corpus.otherShapes)('preserves the recorded $kind ($id) through the selected doorway', async row => {
  const f = fixture(); f.answer(row.raw);
  const result = await f.dispatch().catch(error => error); // The owner observation must retain the real bytes.
  if (row.kind === 'empty-reply-in-recorded-context') expect(result).toBeInstanceOf(Error);
  expect(f.state.calls).toBe(1);
  const store = providerStores(f.root)[0];
  const response = store.facts.find(fact => fact.kind === 'judgment-provider-ProviderJudgmentAttemptRecord'
    && fact.body.record.phase === 'response-observed').body.record;
  const observed = JSON.parse(readFileSync(join(store.directory, 'captures', response.receipt.hash.slice(7)), 'utf8'));
  if (row.raw.length) {
    expect(observed).toMatchObject({ state: 'complete', bytes: row.raw, responseEvidence: {
      eligibility: 'admitted', contract: { parserReference: 'codex-exec-jsonl-events' }, terminal: { providerReason: 'turn.completed' } } });
  } else expect(observed.state).not.toBe('complete');
});

it.each(['auth', 'mutable', 'stop-after-binding', 'tampered-binding', 'wrong-doorway-binding'])('keeps %s closed through the provider owners', async kind => {
  const f = fixture();
  if (kind === 'mutable') f.input.profile = { ...f.input.profile };
  const provider = await doorwayProvider(f.input);
  if (kind === 'auth') f.state.auth = 'apikey';
  if (kind === 'stop-after-binding') f.state.stopped = true;
  const selected = kind === 'tampered-binding' ? { ...provider,
    invocationBinding: { ...provider.invocationBinding, systemPromptDigest: encoded('different').hash } }
    : kind === 'wrong-doorway-binding' ? { ...provider,
      invocationBinding: { ...provider.invocationBinding, doorway: 'claude-code-subscription' } } : provider;
  await expect(f.dispatch(selected)).rejects.toThrow();
  expect(f.state.calls).toBe(0);
});

it.each(['failed-process', 'tool-used', 'malformed', 'over-tokens'])('retains uncertainty or rejection for %s instead of admitting a response', async kind => {
  const f = fixture();
  if (kind === 'failed-process') f.state.code = 1;
  if (kind === 'tool-used') f.state.raw += JSON.stringify({ type: 'item.completed', item: { type: 'command_execution' } }) + '\n';
  if (kind === 'malformed') f.state.raw += 'not-json\n';
  if (kind === 'over-tokens') f.state.raw = f.state.raw.replace(/"output_tokens":\s*\d+/gu, '"output_tokens":999999');
  await expect(f.dispatch()).rejects.toThrow();
  expect(f.state.calls).toBe(1);
});

it.each(['claude-code-subscription', 'codex-cli-subscription'])('measures the exact %s prompt at and over its bound', id => {
  const doorway = subscriptionDoorway(id), framing = doorway.conversationFraming;
  const maximum = doorway.policyFor(model, framing).maxPromptBytes;
  const system = Buffer.byteLength(doorway.systemFor(model, framing));
  const submitted = 'x'.repeat(maximum - system);
  expect(inputMeasurements('', '', submitted, framing, id)).toMatchObject({ system, prompt: maximum, maximum });
  expect(() => requireInputBound('', '', submitted, framing, id)).not.toThrow();
  expect(() => requireInputBound('', '', submitted + 'x', framing, id)).toThrow('complete input bound');
});
